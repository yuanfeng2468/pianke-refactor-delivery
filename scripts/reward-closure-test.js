#!/usr/bin/env node
'use strict'

const fs = require('fs')
const path = require('path')

const root = path.resolve(__dirname, '..')
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8')
const must = (condition, message) => {
  if (!condition) throw new Error(`[REWARD-CLOSURE] ${message}`)
  console.log(`PASS ${message}`)
}

const ad = read('utils/ad.js')
const createOrder = read('uniCloud-alipay/cloudfunctions/createRewardOrder/index.js')
const reportComplete = read('uniCloud-alipay/cloudfunctions/reportAdCompleted/index.js')
const queryOrder = read('uniCloud-alipay/cloudfunctions/queryRewardOrder/index.js')
const callback = read('uniCloud-alipay/cloudfunctions/uni-ad-callback/index.obj.js')
const userCallback = read('uniCloud-alipay/cloudfunctions/userAdCallback/index.js')
const callbackCore = read('uniCloud-alipay/cloudfunctions/common/pianke-common/rewardCallback.js')
const commonIndex = read('uniCloud-alipay/cloudfunctions/common/pianke-common/index.js')
const rewardService = read('uniCloud-alipay/cloudfunctions/common/pianke-common/rewardedVideoService.js')
const orderState = read('uniCloud-alipay/cloudfunctions/common/pianke-common/orderState.js')
const grantIndex = JSON.parse(read('uniCloud-alipay/database/reward_grants.index.json'))
const orderIndex = JSON.parse(read('uniCloud-alipay/database/reward_orders.index.json'))

must(/adInstance\.load\(\)/.test(ad), '首次播放路径主动调用广告 load')
must(/createRewardedVideoAd\(\{[\s\S]{0,260}urlCallback:[\s\S]{0,180}userId:/.test(ad), '订单广告实例在创建参数中透传 userId/urlCallback')
must(!/adInstance\.urlCallback\s*=/.test(ad), '不通过创建后动态赋值 urlCallback，避免原生 SDK 丢失透传参数')
must(/JSON\.stringify\(\{ order_id: orderId, scene \}\)/.test(ad), 'extra 透传订单号和场景，服务端可匹配订单')
must(/reportAdCompleted/.test(ad) && /queryRewardOrder/.test(ad), '完整观看后先上报完成再轮询订单')
must(/cancelRewardOrder/.test(ad) && /finally|catch/.test(ad), '中途退出存在取消订单失败兜底')
must(/status === 'rewarded'/.test(ad) && /pending = true/.test(ad), '客户端只在服务端 rewarded 时确认到账，超时标记 pending')
must(!/meta\.late[\s\S]{0,180}奖励已到账/.test(read('components/RewardedAd.vue')), '奖励组件不把延迟核验误报为已到账')
must(!/meta\.late[\s\S]{0,180}奖励已到账/.test(read('pages/coin/coin.vue')), '金币页不把延迟核验误报为已到账')
must(!/meta\.late[\s\S]{0,180}奖励已到账/.test(read('pages/relax/relax.vue')), '放松页不把延迟核验误报为已到账')
must(/getBusinessDate/.test(createOrder) && /user_daily_stats/.test(createOrder), '创建订单使用 Asia\/Shanghai 权威每日统计')
must(/status: 'client_completed'/.test(reportComplete), '客户端完成只推进到 client_completed，不绕过服务端验证发奖')
must(/client_completed.*verifying.*pending_review.*rewarded/s.test(orderState), '奖励状态机包含客户端完成、核验、待复核和终态链路')
must(/RECOVERABLE_STATUSES/.test(queryOrder) && /command\.in\(RECOVERABLE_STATUSES\)/.test(queryOrder) && /created', 'client_completed', 'verifying', 'verified', 'pending_review'/.test(queryOrder), '恢复查询覆盖全部未终结订单状态')
must(/params\.transId|params\.transaction_id/.test(callbackCore), '回调核心兼容广告平台交易号字段别名')
must(/params\.signature|params\.sig/.test(callbackCore), '回调核心兼容签名字段别名')
must(/isValid: true/.test(callbackCore) && /isValid: false/.test(callbackCore), '回调严格返回 uni-ad 要求的 isValid 结果')
must(/handleRewardCallback/.test(userCallback), '存在官方 userAdCallback 业务入口')
must(/params\.userId|params\.uid/.test(callbackCore), '回调核心兼容用户标识字段别名')
must(/event_id: eventId/.test(commonIndex) && /actor_type/.test(commonIndex), '安全审计写入包含非空 event_id 和 schema 必需字段')
must(/rejected audit write failed/.test(callbackCore), '回调被拒时审计写入失败不会阻断 isValid=false 返回')
must(/order_id: raw/.test(callbackCore) && /order_id: raw/.test(rewardService), 'extra 兼容纯订单号回调格式')
must(/params\.transId|params\.transaction_id/.test(rewardService), '奖励核心服务统一归一化交易号字段')
must(/userAdCallback/.test(read('uniCloud-alipay/cloudfunctions/userAdCallback/package.json')), 'userAdCallback 声明共享模块依赖')
must(/grant_trans_id_unique/.test(JSON.stringify(grantIndex)), '奖励记录存在 trans_id 数据库唯一索引')
must(/grant_order_id_unique/.test(JSON.stringify(grantIndex)), '奖励记录存在 order_id 数据库唯一索引')
must(/uid_idempotency_key_unique/.test(JSON.stringify(orderIndex)), '订单存在用户级幂等唯一索引')
must(/addLedger\(\{ db: transaction/.test(rewardService), '金币奖励在同一事务写入钱包账本')
must(/addRewardGrant\(\{ db: transaction/.test(rewardService), '奖励发放记录在同一事务写入')
must(/status: 'rewarded'/.test(rewardService), '服务端回调成功后才将订单置为 rewarded')
console.log('REWARD_CLOSURE_PASS')
